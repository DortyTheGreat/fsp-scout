def toc(md: str) -> str:
    out = []
    for line in md.splitlines():
        m = re.match(r"^(##|###) (.+)$", line)
        if m and "Содержание" not in m.group(2):
            out.append(("  " if m.group(1) == "###" else "") + f"- {m.group(2)}")
    return "**Содержание**\n\n" + "\n".join(out)


