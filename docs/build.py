def pct(x: float) -> str:
    if 0 < x < 0.05:
        return f"{x * 100:.1f}%".replace(".", ",")
    return f"{x * 100:.0f}%"


def f1(x: float) -> str:
    return f"{x:.1f}".replace(".", ",")


def f3(x: float) -> str:
    return f"{x:.2f}".replace(".", ",")


